#!/usr/bin/env python3
"""Generate deterministic offline English/Italian MP3 speech assets for legacy Android WebViews.
No microphone, network or Android TextToSpeech voices needed for standard vocabulary.
Uses espeak + ffmpeg on the build machine, not on device.
"""
from __future__ import annotations
import ast, hashlib, json, pathlib, re, subprocess, sys, tempfile
ROOT = pathlib.Path(__file__).resolve().parents[1]
DEST = ROOT / 'app' / 'audio'
JS_DEST = ROOT / 'app' / 'js' / 'audio-index.js'
DATA = (ROOT / 'src/js/data.js').read_text(encoding='utf-8')
ENG = (ROOT / 'src/js/games-english.js').read_text(encoding='utf-8')

# Parse row array with a simple quoted 6-field array scanner; the source keeps rows as string arrays.
start = DATA.index('const rows = [')
end = DATA.index('];', start)
segment = DATA[start:end]
entries = re.findall(r"\[\s*'([^']*)'\s*,\s*'([^']*)'\s*,\s*'([^']*)'\s*,\s*'([^']*)'\s*,\s*(\d+)\s*,\s*'([^']*)'\s*\]", segment)
rows = [(en,it,em,cat,int(lvl),cefr) for en,it,em,cat,lvl,cefr in entries]
if len(rows) < 100:
    raise RuntimeError(f'Expected 100+ word rows, found {len(rows)}; do not ship incomplete audio assets')

# Direct words plus individual tokens used to build variable sentences.
items = set()
def add(lang, text):
    text = str(text).strip()
    if text: items.add((lang, text))
for en, it, emoji, cat, level, cefr in rows:
    add('en', en)
    add('it', it)
    for token in re.findall(r"[A-Za-z]+(?:'[A-Za-z]+)?", en): add('en',token.lower())
    for token in re.findall(r"[A-Za-zÀ-ÿ]+(?:'[A-Za-zÀ-ÿ]+)?", it): add('it',token.lower())

# Sentence templates and vocabulary from exercise corpus.
# Full sentences are prerecorded too, so playback works with a single tap on older WebViews.
for answer,sentence in re.findall(r"\{lvl:\d+,a:'([^']+)',s:'([^']+)'", DATA):
    add('en', sentence.replace('___',answer))
for match in re.finditer(r"\bs:\s*'([^']+)'", DATA):
    sentence = match.group(1)
    for token in re.findall(r"[A-Za-z]+(?:'[A-Za-z]+)?", sentence): add('en',token.lower())
for match in re.finditer(r"`([^`]+)`", ENG):
    s = match.group(1)
    if '___' in s:
        for token in re.findall(r"[A-Za-z]+", s): add('en',token.lower())
for token in ('i','you','he','she','we','they','it','a','an','the','is','are','am','can','have','has','see','in','at','on','my','your','this','that','which','where','do','does','not','from','like','want','go','to','with','some','of','and','but','please','there','here','how','who','what','when','why','beautiful','after','before','must','correct','picture','sleeping','run','eat','blue','saturday','tells','stories','feels','keep','visit','use','ride','rides','rides','together','read','books'):
    add('en',token)

items = sorted(items)
index = {}
DEST.mkdir(exist_ok=True, parents=True)
errors = []

def produce(entry):
    lang,text=entry
    normalized=lang+'|'+text.casefold()
    key=hashlib.sha256(normalized.encode('utf-8')).hexdigest()[:20]
    fn=f'{lang}/{key}.mp3'
    dst=DEST / fn
    dst.parent.mkdir(exist_ok=True,parents=True)
    if not dst.exists():
        voice='en-gb' if lang=='en' else 'it'
        tts=subprocess.run(['espeak','-v',voice,'-s','125' if lang=='en' else '135','-a','165','--stdout',text],capture_output=True)
        if tts.returncode != 0 or not tts.stdout:
            return normalized,fn,'espeak failed'
        p=subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-y','-f','wav','-i','pipe:0','-codec:a','libmp3lame','-b:a','48k','-ar','22050','-ac','1',str(dst)],input=tts.stdout,capture_output=True)
        if p.returncode!=0 or not dst.exists() or dst.stat().st_size < 450:
            return normalized,fn,p.stderr[:200].decode('utf-8','ignore')
    return normalized,fn,None

from concurrent.futures import ThreadPoolExecutor
with ThreadPoolExecutor(max_workers=10) as pool:
    for i,(key,fn,err) in enumerate(pool.map(produce,items),1):
        if err: errors.append((key,err))
        else: index[key]=fn
        if i % 80 == 0: print(f'Audio assets: {i}/{len(items)}',flush=True)
if errors:
    raise RuntimeError('Audio generation errors: '+repr(errors[:10]))
# Avoid bundling stale audio from interrupted/previous builds.
used=set(index.values())
for stale in DEST.rglob('*.mp3'):
    if stale.relative_to(DEST).as_posix() not in used:
        stale.unlink()
# Inline JS declaration ES5-safe; en/it keys in lower case.
JS_DEST.write_text('''/* Auto-generated by tools/build_audio_assets.py; audio pronunciations are bundled offline. */\nwindow.LogicLand = window.LogicLand || {};\nwindow.LogicLand.AUDIO_INDEX = '''+json.dumps(index,ensure_ascii=False,separators=(',',':'))+';\n', encoding='utf-8')
summary={'entries':len(index),'vocabulary_rows':len(rows),'audio_size_bytes':sum(x.stat().st_size for x in DEST.rglob('*.mp3'))}
(ROOT/'docs'/'AUDIO_OFFLINE.md').write_text(f'''# English audio v8.1\n\nThe application ships with {summary["entries"]} offline MP3 pronunciations, covering {summary["vocabulary_rows"]} English/Italian vocabulary pairs plus common phrase tokens. Total packaged MP3 data is approximately {summary["audio_size_bytes"]/1024/1024:.1f} MiB.\n\nTap the speaker icon to listen. Local MP3 speech is used first; native Android TextToSpeech and browser speechSynthesis are fallback paths. This avoids relying on a TTS engine/voice pack being installed. For dynamically assembled sentences, a token-by-token audio playlist is used if no whole-sentence audio is available.\n\nThe voice is the offline espeak synthetic voice (not natural speech). Rebuild with `python tools/build_audio_assets.py` after changing vocabulary; the script requires `espeak` and `ffmpeg` on the build machine, not on the device.\n''',encoding='utf-8')
print(json.dumps(summary,ensure_ascii=False,indent=2))
